const sample = JSON.parse(readFileSync(new URL('../contracts/collaboration/examples.json', import.meta.url)));
const unwrap = result => { assert.equal(result.ok, true, JSON.stringify(result)); return result.value; };
const rejects = (result, code) => { assert.equal(result.ok, false); assert.equal(result.error.code, code); };
const principal = { ownerId: 'same-account', deviceId: 'device-a' };
test('collaboration local authorization notifications are isolated, versioned and path-free', () => {
  const changes = createLocalAuthorizationChanges(); const events = [];
  changes.subscribe(() => { throw new Error('bad UI listener'); });
  const unsubscribe = changes.subscribe(e => events.push(e));
  assert.equal(changes.publishCommitted(sample.localAuthorizationEvent), true);
  assert.equal(changes.publishCommitted(sample.localAuthorizationEvent), false);
  unsubscribe();
  assert.equal(changes.publishCommitted({ ...sample.localAuthorizationEvent, bindingRevision: 3 }), true);
  assert.equal(events.length, 1);
  assert.throws(() => changes.publishCommitted({ ...sample.localAuthorizationEvent, localRepoRoot: 'private' }), { code: 'INVALID_INPUT' });
});
test('collaboration mock: two devices, replay, snapshot, pause and defensive copies', async () => {
  const hub = createMockCollaborationHub({ now: () => 100 });
  const a = hub.forPrincipal(principal);
  const b = hub.forPrincipal({ ...principal, deviceId: 'device-b' });
  const events = [];
  a.subscribe(e => events.push(e));
  a.subscribe(() => { throw new Error('UI subscriber failure'); });
  let device = unwrap(await a.registerSelf(sample.deviceConfig));
  assert.deepEqual(unwrap(await a.registerSelf(sample.deviceConfig)), device);
  unwrap(await b.registerSelf({ ...sample.deviceConfig, name: 'B' }));
  const project = unwrap(await a.createProject(sample.projectConfig, 'create-1'));
  assert.deepEqual(unwrap(await a.createProject(sample.projectConfig, 'create-1')), project);
  rejects(await a.createProject({ ...sample.projectConfig, name: 'different' }, 'create-1'), 'REVISION_CONFLICT');
  const report = { ...sample.bindingReport, projectId: project.projectId, deviceId: 'device-b' };
  unwrap(await b.reportBinding(report));
  unwrap(await hub.connect(principal));
  device = unwrap(await a.listDevices()).find(d => d.deviceId === 'device-a');
  unwrap(await a.updateSelf({ ...sample.deviceConfig, acceptingTasks: false }, device.revision));
  const snapshot = unwrap(await b.getSnapshot());
  assert.equal(snapshot.devices.length, 2);
  assert.equal(snapshot.devices.find(d => d.deviceId === 'device-a').acceptingTasks, false);
  assert.ok(!JSON.stringify(snapshot).includes('localRepoRoot'));
  const projection = new CollaborationProjection();
  for (const e of events) assert.equal(projection.apply(e), 'applied');
  assert.deepEqual(projection.getSnapshot(), snapshot);
  assert.equal(projection.apply(events.at(-1)), 'duplicate');
  events[0].payload.name = 'tampered';
  snapshot.devices[0].name = 'tampered';
  assert.notEqual(unwrap(await a.listDevices())[0].name, 'tampered');
  assert.notEqual(unwrap(await a.replay(0))[0].payload.name, 'tampered');
});
test('collaboration mock: account isolation, forged ownership and stale writes rejected', async () => {
  const hub = createMockCollaborationHub();
  const a = hub.forPrincipal(principal);
  const outsider = hub.forPrincipal({ ownerId: 'other-account', deviceId: 'device-a' });
  unwrap(await a.registerSelf(sample.deviceConfig));
  const project = unwrap(await a.createProject(sample.projectConfig, 'create-1'));
  assert.deepEqual(unwrap(await outsider.getSnapshot()).devices, []);
  rejects(await outsider.updateProject(project.projectId, sample.projectConfig, 1), 'NOT_FOUND');
  rejects(await a.registerSelf({ ...sample.deviceConfig, ownerId: 'other-account' }), 'INVALID_INPUT');
  rejects(await a.reportBinding({ ...sample.bindingReport, projectId: project.projectId }), 'DEVICE_SCOPE_MISMATCH');
  rejects(await a.updateSelf(sample.deviceConfig, 99), 'REVISION_CONFLICT');
  const report = { ...sample.bindingReport, deviceId: 'device-a', projectId: project.projectId };
  const first = unwrap(await a.reportBinding(report));
  assert.deepEqual(unwrap(await a.reportBinding(report)), first);
  unwrap(await a.reportBinding({ ...report, state: 'unbound', reasonCode: 'REVOKED', bindingRevision: 2 }));
  rejects(await a.reportBinding(report), 'REVISION_CONFLICT');
  rejects(await a.reportBinding({ ...report, bindingRevision: 2 }), 'REVISION_CONFLICT');
});
test('collaboration mock: old connection cannot disconnect a new connection; journal requires snapshot', async () => {
  const hub = createMockCollaborationHub({ journalLimit: 2 });
  const a = hub.forPrincipal(principal);
  unwrap(await a.registerSelf(sample.deviceConfig));
  const first = unwrap(await hub.connect(principal));
  const second = unwrap(await hub.connect(principal));
  assert.equal(unwrap(await hub.disconnect(principal, first)), false);
  assert.equal(unwrap(await a.listDevices())[0].online, true);
  assert.equal(unwrap(await hub.disconnect(principal, second)), true);
  rejects(await a.replay(0), 'SNAPSHOT_REQUIRED');
  const snapshot = unwrap(await a.getSnapshot());
  assert.deepEqual(unwrap(await a.replay(snapshot.cursor)), []);
});
test('collaboration projection: gaps, stale snapshot, conflicting identity and revisions fail without state mutation', () => {
  const projection = new CollaborationProjection();
  const event = structuredClone(sample.event);
  const gap = { ...event, seq: 2 };
  assert.throws(() => projection.apply(gap), { code: 'SNAPSHOT_REQUIRED' });
  assert.equal(projection.getSnapshot().cursor, 0);
  projection.apply(event);
  assert.throws(() => projection.apply({ ...event, occurredAt: event.occurredAt + 1 }), { code: 'EVENT_CONFLICT' });
  const backwards = { ...event, eventId: 'event-2', seq: 2, revision: 2, payload: { ...event.payload, revision: 2 } };
  assert.throws(() => projection.apply(backwards), { code: 'EVENT_CONFLICT' });
  assert.equal(projection.getSnapshot().cursor, 1);
  assert.throws(() => projection.loadSnapshot({ schemaVersion: 1, cursor: 0, devices: [], projects: [], bindings: [] }), { code: 'SNAPSHOT_REQUIRED' });
  projection.loadSnapshot({ schemaVersion: 1, cursor: 2, devices: [event.payload], projects: [], bindings: [] });
  assert.equal(projection.apply(event), 'stale');
});
test('collaboration simulated authorization can never pass the execution guard', async () => {
  const access = createMockProjectAccess(sample.localBinding, () => 1000);
  const grant = unwrap(await access.resolveAuthorizedWorkspace(sample.authorizationRequest));
  assert.equal(grant.assurance, 'simulation');
  const request = { ...sample.workspaceRequest, authorizationRef: grant.authorizationRef };
  const workspace = unwrap(await access.validateWorkspaceForExecution(request));
  assert.throws(() => assertExecutableWorkspace(workspace, 1000), { code: 'SIMULATION_ONLY' });
  rejects(await access.validateWorkspaceForExecution({ ...request, attemptId: 'other-attempt' }), 'TASK_MISMATCH');
  rejects(await access.resolveAuthorizedWorkspace({ ...sample.authorizationRequest, expectedBindingRevision: 9 }), 'BINDING_CHANGED');
  rejects(await access.resolveAuthorizedWorkspace({ ...sample.authorizationRequest, agentId: 'unknown' }), 'AGENT_UNAVAILABLE');
  const readOnly = createMockProjectAccess({ ...sample.localBinding, permissionCeiling: 'read-only' });
  rejects(await readOnly.resolveAuthorizedWorkspace(sample.authorizationRequest), 'PERMISSION_EXCEEDED');
});
test('collaboration same logical project can resolve to different locally granted roots on two devices', async () => {
  const a = createMockProjectAccess({ ...sample.localBinding, deviceId: 'device-a',
    localRepoRoot: '/home/a/station', taskWorkspaceRoot: '/home/a/workspaces' });
  const b = createMockProjectAccess(sample.localBinding);
  const grantA = unwrap(await a.resolveAuthorizedWorkspace(sample.authorizationRequest));
  const grantB = unwrap(await b.resolveAuthorizedWorkspace(sample.authorizationRequest));
  assert.equal(grantA.projectId, grantB.projectId);
  assert.notEqual(grantA.repoRoot, grantB.repoRoot);
  assert.notEqual(grantA.deviceId, grantB.deviceId);
});
