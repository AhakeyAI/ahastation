    async def publish_generated_text(self,token,base,text):
        """Only test-authored generated bytes; never upgrades a persisted legacy summary."""
        data=text.encode('utf-8');manifest={'version':1,'artifactId':str(uuid.uuid4()),**base,'mediaType':'text/plain;charset=utf-8','byteLength':len(data),'sha256':hashlib.sha256(data).hexdigest(),'chunkSize':32768,'chunkCount':math.ceil(len(data)/32768),'contentComplete':True}
        headers={'Authorization':'Bearer '+token};path='/api/collaboration/v2/text-artifacts'
        r=await self.http.post(path,headers=headers,json=manifest);self.assertEqual(r.status_code,200,r.text)
        for i in range(manifest['chunkCount']):
            part=data[i*32768:(i+1)*32768];r=await self.http.put(path+'/'+manifest['artifactId']+'/chunks/'+str(i),headers=headers,json={'data':base64.b64encode(part).decode(),'sha256':hashlib.sha256(part).hexdigest()});self.assertEqual(r.status_code,200,r.text)
        r=await self.http.post(path+'/'+manifest['artifactId']+'/complete',headers=headers,json={});self.assertEqual(r.status_code,200,r.text)
        return {'summary':text[:4000],'summaryKind':'preview','textArtifact':r.json(),'scopeVersion':0,'tests':'not run; protocol fixture','files':[],'commit':'','prUrl':'','branch':'','report':{'version':1,**base,'summary':text[:4000],'exitConfirmed':True,'files':[],'commit':'','tests':[],'unresolved':['Protocol fixture; no real model or verifier invoked']}}

